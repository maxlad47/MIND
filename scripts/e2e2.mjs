import { chromium } from 'playwright-core'
const base = process.env.BASE ?? 'http://localhost:5180'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: 'light', isMobile: true, hasTouch: true })
const page = await ctx.newPage()
const errors = []
page.on('console', (m) => { if (m.type() === 'error' && !/503/.test(m.text())) errors.push('console: ' + m.text()) })
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
const db = () => page.evaluate(() => JSON.parse(localStorage.getItem('mind.db.v2')))
const ok = (c, m) => console.log((c ? 'OK   ' : 'FAIL ') + m)
await page.goto(base); await page.getByText('Camille').first().click(); await page.waitForTimeout(700)
await page.screenshot({ path: '/tmp/shots/50-light-today.png' })
// navigation vers la semaine suivante pour trouver des séances à déplacer
await page.goto(base + '/#/app/program'); await page.waitForTimeout(500)
await page.getByRole('button', { name: 'Semaine 5', exact: true }).click(); await page.waitForTimeout(400)
const before = await db()
const cam = before.profiles.find((p) => p.firstName === 'Camille')
const prog = before.programs.find((p) => p.clientId === cam.id)
const grips = page.getByLabel('Déplacer')
ok((await grips.count()) > 0, 'poignées en semaine 5 : ' + (await grips.count()))
const b = await grips.first().boundingBox()
await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2); await page.mouse.down()
await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2 + 30, { steps: 5 })
await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2 + 330, { steps: 12 })
await page.screenshot({ path: '/tmp/shots/51-dnd-drag.png' })
await page.mouse.up(); await page.waitForTimeout(600)
await page.screenshot({ path: '/tmp/shots/52-dnd-drop.png' })
const after = await db()
const ap = after.programs.find((p) => p.id === prog.id)
const moved = ap.weeks.flatMap((w) => w.sessions).filter((s) => s.movedFrom)
const conflictSheet = await page.getByText('Ce déplacement crée un conflit').count()
ok(moved.length > 0 || conflictSheet > 0, `déplacement géré (déplacées: ${moved.length}, feuille de conflit: ${conflictSheet})`)
await page.goto(base + '/#/app/progress'); await page.waitForTimeout(800); await page.screenshot({ path: '/tmp/shots/53-light-progress.png' })
console.log('ERRORS:', JSON.stringify(errors, null, 1))
await browser.close()
